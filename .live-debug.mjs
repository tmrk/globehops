import { chromium } from '@playwright/test';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
page.on('request', (r) => { if (/collect/.test(r.url())) console.log('COLLECT', decodeURIComponent(r.url()), '\nBODY', r.postData()); });
await page.goto('https://tmrk.github.io/globehops/?route=CPH-LHR-JFK');
await page.getByRole('button', { name: 'Allow', exact: true }).click();
await page.waitForTimeout(7000);
console.log(JSON.stringify(await page.evaluate(() => window.dataLayer.map((a) => (a && a.length !== undefined ? Array.from(a) : a)))).slice(0, 1500));
await browser.close();
